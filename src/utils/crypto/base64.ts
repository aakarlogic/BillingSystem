// Small helpers: bytes <-> base64 and text <-> bytes (UTF-8, so Marathi/Hindi text is safe).

export function toBase64(bytes: ArrayBuffer | Uint8Array): string {
  const arr = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  let bin = '';
  for (let i = 0; i < arr.length; i += 0x8000) bin += String.fromCharCode(...arr.subarray(i, i + 0x8000));
  return btoa(bin);
}

export function fromBase64(text: string): Uint8Array {
  const bin = atob(text);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

export const utf8 = (text: string) => new TextEncoder().encode(text);
export const fromUtf8 = (bytes: ArrayBuffer) => new TextDecoder().decode(bytes);
